const formatPath = (p) => {
  const parts = [`d: ${JSON.stringify(p.d)}`];
  if (p.opacity !== undefined) parts.push(`opacity: ${p.opacity}`);
  if (p.evenOdd) parts.push("evenOdd: true");
  if (p.stroke) parts.push(`stroke: ${p.stroke}`);
  return `      { ${parts.join(", ")} }`;
};

