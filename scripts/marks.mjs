function circle(cx, cy, r) {
  return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 ${-r * 2} 0z`;
}

function roundedRect(x, y, w, h, r) {
  return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`;
}

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

async function fetchMark(icon, layers = {}) {
  const [prefix, name] = icon.split(":");
  const res = await fetch(`${API}/${prefix}/${name}.svg`);
  if (!res.ok) throw new Error(`${icon}: HTTP ${res.status}`);
  const svg = await res.text();
  const viewBox = attr(svg, "viewBox");
  const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(([tag]) => {
    const fill = attr(tag, "fill");
    if (fill === "none") return null;
    const path = { d: attr(tag, "d") };
    const opacity = fill in layers ? layers[fill] : Number(attr(tag, "opacity") ?? 1);
    if (opacity !== 1) path.opacity = opacity;
    if (attr(tag, "fill-rule") === "evenodd") path.evenOdd = true;
    return path;
  });
  if (!viewBox || !paths.length) throw new Error(`${icon}: no paths`);
  return { viewBox, paths: paths.filter(Boolean) };
}

